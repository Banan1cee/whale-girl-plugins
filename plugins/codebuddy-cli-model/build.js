'use strict';
/**
 * Zero-dependency ZIP builder (Node built-ins only).
 * Produces packages/<Id>-<Version>.zip whose ROOT contains exactly
 * plugin.json and plugin.js, as required by the market validate.py for Api 4.
 * The version is read from plugin.json, so bumping Version is all you need.
 *
 *   node build.js
 *
 * Fixed DOS timestamps make the build reproducible: same sources -> same ZIP.
 */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const HERE = __dirname;
const MANIFEST = JSON.parse(fs.readFileSync(path.join(HERE, 'plugin.json'), 'utf8'));
const OUT = path.resolve(HERE, '..', '..', 'packages', MANIFEST.Id + '-' + MANIFEST.Version + '.zip');
const FILES = ['plugin.json', 'plugin.js'];

const CRC_TABLE = new Uint32Array(256);
for (let i = 0; i < 256; i++) {
  let c = i;
  for (let k = 0; k < 8; k++) c = (c & 1) ? (0xEDB88320 ^ (c >>> 1)) : (c >>> 1);
  CRC_TABLE[i] = c >>> 0;
}
function crc32(buf) {
  let crc = 0xFFFFFFFF;
  for (let i = 0; i < buf.length; i++) crc = CRC_TABLE[(crc ^ buf[i]) & 0xff] ^ (crc >>> 8);
  return (crc ^ 0xFFFFFFFF) >>> 0;
}

const DOS_TIME = 0;       // 00:00:00
const DOS_DATE = 0x5C21;  // 2026-01-01

function zip(entries) {
  const localParts = [], centralParts = [];
  let offset = 0;
  for (const [name, data] of entries) {
    const nameBuf = Buffer.from(name, 'utf8');
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0, 6);
    local.writeUInt16LE(0, 8);            // store (no compression)
    local.writeUInt16LE(DOS_TIME, 10);
    local.writeUInt16LE(DOS_DATE, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(data.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBuf.length, 26);
    local.writeUInt16LE(0, 28);
    localParts.push(local, nameBuf, data);

    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4);
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0, 8);
    central.writeUInt16LE(0, 10);
    central.writeUInt16LE(DOS_TIME, 12);
    central.writeUInt16LE(DOS_DATE, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(data.length, 20);
    central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(nameBuf.length, 28);
    central.writeUInt16LE(0, 30);
    central.writeUInt16LE(0, 32);
    central.writeUInt16LE(0, 34);
    central.writeUInt16LE(0, 36);
    central.writeUInt32LE(0, 38);
    central.writeUInt32LE(offset, 42);
    centralParts.push(central, nameBuf);

    offset += local.length + nameBuf.length + data.length;
  }
  const central = Buffer.concat(centralParts);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(0, 4);
  end.writeUInt16LE(0, 6);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(central.length, 12);
  end.writeUInt32LE(offset, 16);
  end.writeUInt16LE(0, 20);
  return Buffer.concat([...localParts, central, end]);
}

const entries = FILES.map(name => [name, fs.readFileSync(path.join(HERE, name))]);
const data = zip(entries);
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, data);
console.log('version  :', MANIFEST.Version);
console.log('ZIP      :', OUT);
console.log('size     :', data.length, 'bytes (Api 4 limit 16 MiB)');
console.log('entries  :', FILES.join(', '));
console.log('sha256   :', crypto.createHash('sha256').update(data).digest('hex'));
console.log('\nThe catalog index*.json is generated by the market CI - do not edit it by hand.');
